/** Shuffle bags avoid repeats until every quote in that category has been used. */
export class QuoteBag {
  private bag:string[]=[];
  private last:string|undefined;
  constructor(private readonly source:readonly string[],private readonly choose:(max:number)=>number=max=>randomInt(max)) {
    if (new Set(source).size<2) throw new Error('A quote bag needs at least two unique quotes.');
  }
  next():string {
    if (!this.bag.length) {
      this.bag=[...new Set(this.source)];
      for (let i=this.bag.length-1;i>0;i--) {
        const j=this.choose(i+1);
        [this.bag[i],this.bag[j]]=[this.bag[j]!,this.bag[i]!];
      }
      if (this.bag[this.bag.length-1]===this.last) [this.bag[0],this.bag[this.bag.length-1]]=[this.bag[this.bag.length-1]!,this.bag[0]!];
    }
    const quote=this.bag.pop()!;
    this.last=quote;
    return quote;
  }
}
